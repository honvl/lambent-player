#!/usr/bin/env python3
"""Writes lib/l10n/lambent_localizations.dart from upstream's AppLocalizations.

Upstream's translation files stay exactly as Moonfin ships them, so merging
upstream never conflicts on them. Lambent's name goes in when the app loads its
strings instead: LambentLocalizations wraps whichever AppLocalizations Flutter
picked and passes every string through `lambentBranded`.

Run it after every upstream merge and after `flutter gen-l10n`:

    python3 tool/gen_lambent_l10n.py

The class extends AppLocalizations, whose members are all abstract, so a string
upstream adds and this file doesn't cover yet is a compile error rather than a
Moonfin slipping through.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "lib/l10n/app_localizations.dart"
TARGET = ROOT / "lib/l10n/lambent_localizations.dart"

# Strings that keep upstream's wording: the folder downloads go to on disk is
# still named Moonfin, and these name the Moonfin plugin and its tools.
KEEP = {
    "downloadsVisibleToOtherApps",
    "saveToDownloadsFolderDescription",
    "settingsSupportMoonfin",
    "savedThemesDescription",
    "themeEditorSubtitle",
}

# Strings Lambent words its own way, as Dart expressions.
OVERRIDES = {
    "sourceCodeUrl": "'https://github.com/honvl/lambent-player'",
    # Lambent Server has no watch parties, and English is the only language
    # that said otherwise.
    "settingsPlaybackSubtitle": (
        "localeName.startsWith('en')\n"
        "      ? 'Player, quality, audio, subtitles, and skipping'\n"
        "      : lambentBranded(_inner.settingsPlaybackSubtitle)"
    ),
}

GETTER = re.compile(r"^  String get (\w+);$")
METHOD = re.compile(r"^  String (\w+)\((.*)\);$")


def members(source: str):
    lines = source.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        # A long signature wraps over several lines; join it back up.
        if line.startswith("  String ") and "(" in line and not line.endswith(";"):
            while not line.endswith(";"):
                i += 1
                line += " " + lines[i].strip()
            line = line.replace("( ", "(").replace(", )", ")")
        if m := GETTER.match(line):
            yield m.group(1), None
        elif m := METHOD.match(line):
            params = [p.strip() for p in m.group(2).split(",") if p.strip()]
            yield m.group(1), params
        i += 1


def body(name, params):
    call = f"_inner.{name}" + (
        "" if params is None else "(" + ", ".join(p.split()[-1] for p in params) + ")"
    )
    if name in OVERRIDES:
        return OVERRIDES[name]
    if name in KEEP:
        return call
    return f"lambentBranded({call})"


def main():
    out = [
        "// Generated by tool/gen_lambent_l10n.py from app_localizations.dart.",
        "// Don't edit by hand: run the script again after an upstream merge.",
        "",
        "// ignore_for_file: type=lint",
        "",
        "import 'package:flutter/widgets.dart';",
        "import 'package:flutter_localizations/flutter_localizations.dart';",
        "",
        "import 'app_localizations.dart';",
        "",
        "/// Upstream's wording with Lambent's name, leaving Moonfin's own project",
        "/// names (Moonfin-Client, Moonfin-Core) alone so links keep working.",
        "/// Serbian writes the name in Cyrillic.",
        "String lambentBranded(String text) {",
        "  if (text.contains('Moonfin')) text = text.replaceAll(_moonfin, 'Lambent');",
        "  if (text.contains('Мунфин')) text = text.replaceAll('Мунфин', 'Ламбент');",
        "  return text;",
        "}",
        "",
        "final _moonfin = RegExp(r'Moonfin(?!-(?:Client|Core)\\b)');",
        "",
        "/// Loads upstream's strings and hands them out as [LambentLocalizations].",
        "class LambentLocalizationsDelegate",
        "    extends LocalizationsDelegate<AppLocalizations> {",
        "  const LambentLocalizationsDelegate();",
        "",
        "  @override",
        "  Future<AppLocalizations> load(Locale locale) async =>",
        "      LambentLocalizations(await AppLocalizations.delegate.load(locale));",
        "",
        "  @override",
        "  bool isSupported(Locale locale) =>",
        "      AppLocalizations.delegate.isSupported(locale);",
        "",
        "  @override",
        "  bool shouldReload(LambentLocalizationsDelegate old) => false;",
        "}",
        "",
        "class LambentLocalizations extends AppLocalizations {",
        "  LambentLocalizations(this._inner) : super(_inner.localeName);",
        "",
        "  final AppLocalizations _inner;",
        "",
        "  static const LocalizationsDelegate<AppLocalizations> delegate =",
        "      LambentLocalizationsDelegate();",
        "",
        "  /// [AppLocalizations.localizationsDelegates] with this one in its place.",
        "  static const List<LocalizationsDelegate<dynamic>> localizationsDelegates =",
        "      <LocalizationsDelegate<dynamic>>[",
        "        delegate,",
        "        GlobalMaterialLocalizations.delegate,",
        "        GlobalCupertinoLocalizations.delegate,",
        "        GlobalWidgetsLocalizations.delegate,",
        "      ];",
    ]
    count = 0
    for name, params in members(SOURCE.read_text(encoding="utf-8")):
        count += 1
        out.append("")
        out.append("  @override")
        if params is None:
            out.append(f"  String get {name} =>")
        else:
            out.append(f"  String {name}({', '.join(params)}) =>")
        out.append(f"      {body(name, params)};")
    out.append("}")
    TARGET.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{TARGET.relative_to(ROOT)}: {count} strings")


if __name__ == "__main__":
    main()
